/**
  ******************************************************************************
  * @file    ackermann.h
  * @brief   齿条式阿卡曼 逆运动学 —— 接口定义
  *
  * ============================================================================
  *  一、你的车是怎么转向的？
  * ============================================================================
  *
  *        6020 电机
  *           ↓ 转
  *        小齿轮
  *           ↓ 齿轮齿条
  *      ←──── 齿条 ────→      （中心到左右各 23mm 行程，软件限位 22mm）
  *        ↓          ↓
  *      拉杆        拉杆
  *        ↓          ↓
  *     左前轮      右前轮
  *
  *  关键点：齿条只有【一个】输入。
  *  齿条往左走，两个前轮就一起往左转；
  *  具体左轮转多少度、右轮转多少度，
  *  是由"梯形拉杆"的机械结构决定的，程序改不了也不用管。
  *
  *  所以程序要做的事只有两件：
  *      ① 算出齿条应该走多少毫米  -> 交给 6020 的位置环
  *      ② 算出左右后轮各转多少    -> 交给两个 3508 的速度环
  *
  * ============================================================================
  *  二、为什么后轮要"差速"？（这就是阿卡曼的核心）
  * ============================================================================
  *
  *  车向左转弯时，四个轮子走的圆不一样大：
  *
  *                左后轮              右后轮
  *                   ●                   ●
  *                  ╱                     ╲
  *                 ╱   ← 走的圆小           ╲  ← 走的圆大
  *                ╱                           ╲
  *               ●───────── 圆心 ─────────────●
  *                          ↑
  *                        转弯半径 R
  *
  *  如果两个后轮转速一样，内侧轮就会"拖地"（打滑），
  *  车会走不顺、轮胎磨损、还会影响循迹。
  *
  *  所以：内侧后轮要转得慢一点，外侧后轮要转得快一点。
  *
  *  公式（R 是转弯半径，B 是【后】轮距 = 332mm）：
  *      内侧轮速度 = 车速度 × (R - B/2) / R
  *      外侧轮速度 = 车速度 × (R + B/2) / R
  *
  * ============================================================================
  *  三、转弯半径 R 怎么来？
  * ============================================================================
  *  用"自行车模型"（把四个轮子简化成前后两个轮子）：
  *
  *      R = 轴距 L / tan(前轮转角 δ)
  *
  *  你的车：L = 296.33mm
  *  前轮转角 δ 由齿条位置决定（线性近似）：
  *
  *      δ = 齿条位置 / 22mm × 满行程时的最大转角
  *
  * ============================================================================
  *  四、前轮距 342 和后轮距 332 分别用在哪？
  * ============================================================================
  *     后轮距 332 -> 算后轮差速（真正控制用）
  *     前轮距 342 -> 算"理想阿卡曼的两个前轮角度"（只用来对比/调试）
  *
  *  为什么要算前轮角度？因为阿卡曼的定义就是：
  *      内前轮转角 > 外前轮转角，而且满足
  *          cot(内) - cot(外) = 前轮距 / 轴距
  *  你算出来之后，可以拿量角器去量实车的前轮，
  *  看看你的梯形拉杆设计得对不对。
  *  ★ 这两个角度【不发给任何电机】，只是给你看的。
  *
  * ============================================================================
  *  五、单位约定（★ 一定要对上 ★）
  * ============================================================================
  *      输入 base_rpm ：直行时后轮的目标转速，单位【转子 rpm】
  *      输入 rack_mm  ：齿条目标位置，单位【毫米】，正 = 向左
  *      输出 rear_rpm ：左右后轮目标转速，单位【转子 rpm】
  *      输出 rack_mm  ：实际下发给转向电机的齿条位置（已限幅）
  *      输出 delta_deg：等效前轮转角（调试用）
  *      输出 front_deg：理想的左/右前轮转角（调试用，不发电机）
  ******************************************************************************
  */
#ifndef __ACKERMANN_H
#define __ACKERMANN_H

#include "main.h"

/**
  * @brief 运动解算的输出
  */
typedef struct {
    float rear_rpm[2];    /* [0] = 左后轮，[1] = 右后轮。单位：转子 rpm */
    float rack_mm;        /* 齿条目标位置，单位：毫米，正 = 向左 */
    float delta_deg;      /* 等效前轮转角（虚拟中轮），单位：度，调试用 */
    float front_deg[2];   /* [0] = 左前轮，[1] = 右前轮。
                             理想阿卡曼角度，单位：度。
                             ★ 只用来量车对比，不发给任何电机 */
} Ackermann_Out_t;

/**
  * @brief  齿条式阿卡曼逆运动学解算
  * @note   调用位置：App/Task/task_chassis.c 的 Task_Chassis_Loop() 第 ③ 步，
  *                   每 1 毫秒调用一次
  * @note   实现位置：App/Algorithm/ackermann.c
  * @param  base_rpm  摇杆给的速度，单位【转子 rpm】（直行时后轮就转这么多）
  * @param  rack_mm   摇杆给的转向，单位【毫米】（正 = 向左）
  * @param  out       解算结果（函数往里写，调用者不用初始化）
  * @retval  无
  */
void Ackermann_Solve(float base_rpm, float rack_mm, Ackermann_Out_t *out);

#endif
