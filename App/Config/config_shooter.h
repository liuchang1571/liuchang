/**
  ******************************************************************************
  * @file    config_shooter.h
  * @brief   发射机构（2 个摩擦轮 + 拨弹盘，全是 3508）
  *
  * ============================================================================
  *  模式（摇杆拨杆）
  * ============================================================================
  *   S1 = 1  单发模式：两个摩擦轮起转等待；S2 拨到 1 一次 -> 拨弹盘走一格
  *   S1 = 2  连发模式：两个摩擦轮起转等待；S2 按住         -> 按固定间隔一格一格
  *   S1 = 其它            两个摩擦轮停、拨弹盘不动
  *
  * ============================================================================
  *  CAN1 的 0x200 一帧 4 个（槽位 = ID-1）
  * ============================================================================
  *   槽0 = pitch(1)   槽1 = 拨弹盘(2)   槽2 = 摩擦轮左(3)   槽3 = 摩擦轮右(4)
  ******************************************************************************
  */
#ifndef __CONFIG_SHOOTER_H
#define __CONFIG_SHOOTER_H


/* ============================================================================
 *  一、电机 ID（CAN1，0x200 帧）
 * ==========================================================================*/
#define FEEDER_3508_ID      2       /* 拨弹盘   -> 反馈 0x202 */
#define FRIC_L_3508_ID      3       /* 摩擦轮左 -> 反馈 0x203 */
#define FRIC_R_3508_ID      4       /* 摩擦轮右 -> 反馈 0x204 */

/* ============================================================================
 *  二、摩擦轮（速度环）
 * ==========================================================================*/
/* 目标转速（转子 rpm）。★ 待调：
 *   3508 满量程 9000；摩擦轮一般 4000~7000。
 *   太高会打碎弹丸，太低会卡弹。从 5000 起，按弹道调。 */
#define FRIC_RPM            5000.0f

/* 加速斜率（转子 rpm/秒）：5000/15000 ≈ 0.33 秒到速（"迅速到达"，但不像阶跃那样冲电流） */
#define FRIC_ACCEL_RPM_S    15000.0f

/* 两个轮子必须反向转（把弹丸夹住往前送）。
 * 标定：给正目标，看轮子是不是把弹丸往外送；反了就把对应那个取负。 */
#define FRIC_DIR_L          (+1.0f)
#define FRIC_DIR_R          (-1.0f)

#define FRIC_CUR_MAX        10000.0f    /* 电流限幅（满量程 ±16384） */
#define FRIC_VEL_KP         12.0f       /* 电流 / 转子 rpm */
#define FRIC_VEL_KI         0.30f
#define FRIC_VEL_I_MAX      300.0f

/* 摩擦轮没到速不许拨弹（防止慢速把弹丸挤在轮子里卡死）
 * 1 = 开启；到速判据 = 两个轮子都 >= FRIC_RPM × FRIC_READY_RATIO */
#define FRIC_READY_GATE     1
#define FRIC_READY_RATIO    0.5f

/* ============================================================================
 *  三、拨弹盘（位置环 + 速度环，一格一格走）
 * ==========================================================================*/
/* 一格 = 多少编码器计数（【转子】计数，8192 = 转子转一圈）
 *
 *   本车：M3508（19:1 减速箱）+ 9 格拨盘，盘与输出轴 1:1
 *        8192 × 19.2032 / 9 = 17479      （减速箱精确比 3591/187）
 *        若按标称 19:1 算      = 17294
 *
 *   ★ 验证：连打 9 发 = 盘正好转一整圈，看能不能回到初始位置。
 *           差约 4°（一格 40° 的 10%）就是填错了，换成另一个值。
 *   ★ 方向反了就把这个数改成负的。 */
#define FEEDER_COUNTS_PER_SLOT   -17479.0f

/* ============================================================================
 *  ★ 下面这几个拨弹盘参数，现在都是【上电默认值】
 * ============================================================================
 *  真正的运行值在 driver_shooter.c 顶部的同名小写变量里：
 *      FEEDER_POS_KP            -> feeder_pos_kp
 *      FEEDER_POS_DEADBAND      -> feeder_pos_deadband
 *      FEEDER_SPD_LIMIT_RPM     -> feeder_spd_limit_rpm
 *      FEEDER_SPD_KP            -> feeder_spd_kp
 *      FEEDER_SPD_KI            -> feeder_spd_ki
 *      FEEDER_SPD_FILTER_ALPHA  -> feeder_spd_filter_alpha
 *      FEEDER_CUR_SLEW          -> feeder_cur_slew
 *      FEEDER_COUNTS_PER_SLOT   -> feeder_counts_per_slot
 *
 *  调参时直接改【小写变量】（FreeMASTER 在线改，立刻生效）；
 *  调稳了再把这里的默认值改成同一个数，这样重新上电也是对的。
 * ==========================================================================*/

/* 位置环：误差(计数) -> 速度(转子 rpm) */
#define FEEDER_POS_KP           0.5f
#define FEEDER_SPD_LIMIT_RPM    900.0f      /* 位置环输出限幅 */

/* 速度环：转子 rpm -> 电流
 * ★ 9.0：一格误差 17479 时位置环会算出 8739rpm，被 FEEDER_SPD_LIMIT_RPM 限到 900，
 *   所以起步电流 = 9 × 900 ≈ 8100（约满量程的一半），起步很有劲。
 *   全程 900rpm 巡航 → 一格约 141ms，加上收尾约 190ms。 */
#define FEEDER_SPD_KP           5.0f
#define FEEDER_SPD_KI           0.0f
#define FEEDER_SPD_I_MAX        6000.0f
#define FEEDER_CUR_MAX          16000.0f
#define FEEDER_CUR_SLEW         4000        /* 电流每 ms 最多变化多少（抑制冲击声） */
#define FEEDER_SPD_FILTER_ALPHA 0.3f        /* 速度反馈一阶低通 */

/* 到位死区：误差小于它 -> 速度指令给 0，电机彻底安静
 * 170 计数 ≈ 一格的 1.0%（盘面 0.39°）。误差不累积：目标是绝对计数，残余无害。
 * ★ 不能设太小：电机走到"摩擦地板"（大约还差 100~200 计数）就停了，
 *   死区比它还小的话永远触发不了，会一直挂着一个小电流。
 * ★ 这里【不再】做"最小速度"补偿：那是开关式补丁，会在到位的时候来回蹭
 *   （60rpm 冲过死区 -> 误差变负 -> 反向再给 60rpm）。推力改由 FEEDER_SPD_KP 给。 */
#define FEEDER_POS_DEADBAND     170.0f

/* ============================================================================
 *  四、时序
 * ==========================================================================*/
/* 连发间隔：333ms ≈ 3 发/秒
   （改射速就用这个公式：1000 / 射速。比如 5 发/秒 -> 200） */
#define FEEDER_AUTO_INTERVAL_MS 333
#define FEEDER_BLOCK_START_MS   200     /* 发出这一格后先宽限这么久，再开始判卡弹 */
#define FEEDER_BLOCK_MS         400     /* "有误差但转速≈0" 持续这么久 -> 判定卡弹 */
#define FEEDER_STALL_RPM        5.0f    /* 转速低于它算"没动" */
#define FEEDER_BACK_SLOTS       1       /* ★ 卡弹回退几格（1 = 按你的要求；2 更保险） */
#define FEEDER_RETRY_MS         200     /* 单发模式：回退后多久自动重试一格 */
#define FEEDER_RETRY_MAX        3       /* 连续重试上限，超过就等松手重拨 */

#endif /* __CONFIG_SHOOTER_H */
