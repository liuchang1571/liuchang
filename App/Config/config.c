/**
  ******************************************************************************
  * @file    config.c
  * @brief   全局变量的"定义"处
  *
  * ============================================================================
  *  为什么变量要单独放一个 .c 文件？
  * ============================================================================
  *  C 语言的规矩：
  *     一个变量可以"声明"很多次，但只能"定义"一次。
  *
  *     声明（extern）：只是告诉别人"有这么个东西"
  *     定义（不写 extern）：真正分配内存
  *
  *  config.h 里写的是 extern（声明），
  *  真正的内存分配全部写在这个文件里。
  *
  *  如果把定义写在头文件里，那么每个 #include 它的 .c 文件
  *  都会定义一份，链接的时候就会报
  *     "multiple definition of rc_data"
  ******************************************************************************
  */
#include "config.h"

/* ---------------------------------------------------------------------------
 *  遥控器原始数据
 * ---------------------------------------------------------------------------
 *  一块 18 字节的内存。串口中断收到一帧就 memcpy 到这里。
 *
 *  上电时编译器会把它全部清成 0，
 *  所以第一帧数据到达之前，rc_data 里全是 0（解出来的摇杆值也是 0）。
 *  这个"0"是个非法值，不过没关系 ——
 *  下面的 rc_lost_flag 上电初值是 1（关控），
 *  底盘任务看到关控就直接给 0 速度，根本不会去读摇杆。
 * ------------------------------------------------------------------------- */
RC_Ctl_Define_t rc_data;

/* ---------------------------------------------------------------------------
 *  关控标志
 * ---------------------------------------------------------------------------
 *  ★ 上电初值为什么是 1（关控）而不是 0（正常）？
 *
 *  上电后第一帧遥控器数据要等十几毫秒才能收到。
 *  如果初值是 0（正常），主板会以为"遥控器正常、摇杆在中位"，
 *  然后按中位去跑。
 *  但万一这时候摇杆其实是被推着的呢？车就会突然动一下。
 *
 *  所以上电先按"关控"处理，
 *  等 task_rc.c 真的收到一帧数据，才会把它清成 0。
 *  这是最安全的做法。
 * ------------------------------------------------------------------------- */
uint8_t rc_lost_flag = 1;

/* ---------------------------------------------------------------------------
 *  初始化完成标志
 * ---------------------------------------------------------------------------
 *  0 = 外设还没启动（CAN 还没 Start、串口 DMA 还没开始收）
 *  1 = 全部启动好了
 *
 *  ★ 为什么要加 volatile？
 *    因为这个变量在"初始化任务"里被写成 1，
 *    在"底盘任务"里被反复读取。
 *    不加 volatile 的话，编译器可能会想：
 *      "这个变量在这个函数里没人改它，那我读一次存寄存器里就行了"
 *    结果底盘任务永远读到的是 0，卡在等待里出不来。
 *    volatile 就是告诉编译器："这个变量随时可能被别人改，每次都去内存里读"。
 * ------------------------------------------------------------------------- */
volatile uint8_t g_sys_ready = 0;
