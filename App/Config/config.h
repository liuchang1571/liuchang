/* 齿条物理行程：从中心到最左（或最右）是 46mm。
 * 这是机械硬限位，超过就会顶坏东西。只作为参考值。 */
#define STEER_RACK_MM_HW  46.0f

/* 软件限位：允许齿条走到 ±45mm（比物理 ±46mm 小 1mm）。
 * ★ 必须比物理限位小，否则齿条会一直顶死在机械块上，
 *   电机持续出力、发热、烧电机。
 *
 * 注意：C 语言的 #if 不能比较小数（只能是整数），
 *       所以这里没法用"编译期检查"来保证 45 < 46，
 *       只能靠你自己看一眼。改的时候记得 软件限位 一定 < 物理限位。 */
#define STEER_RACK_MM_MAX  45.0f

/* ★★★ 下面 3 个必须你自己标定，我给的只是占位值 ★★★
 *
 * 【1】STEER_CENTER_RAW —— 齿条在正中间时，6020 的编码器值
 *      标定：
 *        1. 车架空，烧程序进板子
 *        2. 调试器看 Steer_Get()->actual_raw
 *        3. 用手把齿条推到中间位置（用尺子量，左右各 46mm）
 *        4. 记下那一刻的 actual_raw，填到这里
 *
 * 【2】STEER_RAW_PER_MM —— 齿条每走 1mm，编码器变化多少个计数
 *      标定：
 *        1. 齿条在中间，记下编码器值 raw_a
 *        2. 把齿条推到 +45mm 处（尺子量），记下 raw_b
 *        3. STEER_RAW_PER_MM = (raw_b - raw_a) / 45
 *      如果你知道小齿轮的模数和齿数，也可以算：
 *        齿条每转移动量 = 3.14159 × 模数 × 齿数（mm）
 *        STEER_RAW_PER_MM = 8192 / 齿条每转移动量
 *
 *      ★ 如果标完之后发现"摇杆往左推，齿条往右走"，
 *        【千万不要】在这个数字前面加负号！
 *
 *        原因：这个数字除了"毫米 → 编码值"，还被 PID 用来算
 *              err_mm = err_cnt / STEER_RAW_PER_MM
 *        它一变负，误差也跟着翻号，位置环就从【负反馈】变成【正反馈】：
 *        你让它往右，它反而往左用力，一直顶到限位被切断 ——
 *        表现就是"怎么推都不理你"。
 *
 *        正确做法：这里保持正数（25.9），方向在 STEER_DIR 里翻。
 *
 * 【3】STEER_MAX_DEG —— 齿条打满时，前轮的【等效】转角
 *      为什么要"等效"，而不是直接量一个轮？
 *        因为代码里用的是单轮自行车模型（一个角对应一个转弯半径），
 *        而实车有两个不同的前轮角，所以要折算成一个等效值：
 *            等效角 ≈ (内轮角 + 外轮角) / 2
 *
 *      你实测：内轮 35°、外轮 25°  ->  等效 30°
 *
 *      ★ 顺带算出来的两个数（供参考）：
 *        内轮 35° 单独看 -> R = 423mm
 *        外轮 25° 单独看 -> R = 636mm
 *        等效 30°        -> R = 513mm（满方向时的实际转弯半径）
 *
 *      ★ 你的梯形是"欠阿克曼"（内外轮差 10°，理想要 20°），
 *        会造成推头。这个用 ACKERMANN_GAIN 补偿，见第 5 部分。
 */
/* ★ 下面两个已按实测值填好：中间 6552 / 最左 7742 / 最右 5358
 *   跨度 2384 计数，对应机械行程 ±46mm（共 92mm）
 *   -> 2384 / 92 = 25.9 计数/mm */
#define STEER_CENTER_RAW   6552     /* 齿条居中时的编码器值 0~8191 */
#define STEER_RAW_PER_MM   25.9f    /* 每毫米对应多少编码器计数（正数 = 往左编码值变大） */
#define STEER_MAX_DEG      30.0f    /* 齿条打满 ±45mm 时前轮转角（度）★ 实测等效值 */

/* 转向方向（摇杆往右推，齿条应该往右走）。
 *    1.0f = 正好
 *   -1.0f = 反了，用这个   ← 你现在实测反了，所以填 -1
 *
 * ★ 这是【唯一】应该用来翻方向的开关。
 *   绝对不要改 STEER_RAW_PER_MM 的符号 —— 那个会同时把 PID 的误差换算
 *   翻号，位置环变成正反馈，电机就会一直顶着限位、怎么推都不理你。
 *
 * ★ 它只翻"摇杆 → 齿条目标"这一段，不影响：
 *     - 编码值限位（限位拿实测两端当边界，和方向无关）
 *     - PID 稳定性（误差仍然是"目标 − 实际"，符号自洽）
 *     - 上电保护（第一帧仍然把目标设成当前位置） */
#define STEER_DIR  (-1.0f)

/* ============================================================================
 *  第 4.2 部分：★★ 转向电机的"编码值"软件限位 ★★
 * ============================================================================
 *  实测：中间 6552、最左（左转）7742、最右（右转）5358。
 *
 *  逻辑：目标编码值跑到 [5358, 7742] 之外时，压回最近的边界。
 *
 *  ★ 为什么不直接写  if (t > 7742) t = 7742;  ?
 *
 *    那种写法只在你现在这组数字下成立。万一哪天电机重新装配、小齿轮错开
 *    半圈，两端编码值就可能跨过 0/8191 的接缝（比如变成 7900 和 100）。
 *    这时"比大小"得到的最小/最大值会是 100 和 7900 ——
 *    而真正的行程恰恰是"100 反向绕一圈到 7900"，
 *    限位反而会把齿条夹进错误的那一段，比不限位更危险。
 *
 *    所以代码里统一换到"相对中位的计数"坐标（-4096 ~ +4096），
 *    由 norm_cnt 处理回绕，任何装配位置都不会算错。
 * ==========================================================================*/

/* 开关：1 = 启用编码值限位；0 = 只用上面的 ±45mm 限位 */
#define STEER_RAW_LIMIT_ENABLE  1

/* 内缩余量（编码计数）。
 * 你实测的两端是"齿条已经顶住机械限位块"的位置。
 * 目标直接贴着那儿，只要实测值略微超出真实可达位置（金属有弹性、
 * 手推时的读数偏差），位置环就会一直用力顶，电机持续发热。
 * 往里缩一点更安全：55 计数 ≈ 2.1mm（你这里 25.9 计数/mm）。
 * 想让目标直接贴到极限，就改成 0。 */
#define STEER_RAW_MARGIN_CNT    55

/* 越限保护余量（编码计数）：实测位置超出限位超过这么多，就切断输出。
 * 正常走车到不了这么远，它防的是编码值跳变（比如线松了跳数）。 */
#define STEER_RAW_GUARD_CNT     130

/* 转向电机的输出限幅。
 * 电压控制模式满量程 ±30000，这里只给 15000，
 * 是为了"万一程序跑飞"也不要用最大力气去撞限位。 */
#define STEER_OUT_MAX  15000

/* ---- 转向位置环 PID ----
 *  输入：误差，单位是【毫米】（齿条还差多少毫米到位）
 *  输出：电压 -15000 ~ +15000
 *
 *  KP = 200 的意思是"差 1mm，就给 200 的电压"。
 *  差满行程 45mm 就是 9000，占限幅 15000 的 60%，比较温和。
 *
 *  调参：
 *    KI 先保持 0（顶限位时积分会越攒越大，很危险）
 *    KP 从 300 开始往上试，
 *       打方向有劲、到位后不来回晃，就差不多了
 *       如果到位后来回晃，说明 KP 太大，往下调 */
#define STEER_PID_KP  450.0f
#define STEER_PID_KI  0.0f
#define STEER_PID_KD  0.0f

