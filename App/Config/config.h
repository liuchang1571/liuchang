#define WHEEL_TRACK_FRONT_MM  342.0f

/* 后轮距：两个后轮心的距离 = 332mm
 * ★ 这个才是算后轮差速真正要用的，
 *   因为我们是给两个后轮分别指定转速。 */
#define WHEEL_TRACK_REAR_MM  332.0f

/* ============================================================================
 *  后轮差速强度微调（★ 补偿转向梯形的"欠阿克曼"）
 * ============================================================================
 *  实测你的转向几何（齿条到机械限位时）：
 *      内前轮 35°   外前轮 25°   差 10°
 *  而理想阿克曼要求：
 *      外轮 25° 时内轮应该 45.3°   →  内外轮差应该 20.3°
 *
 *  也就是说【你的内外轮差只有理想值的一半】，这是拉杆几何决定的，
 *  软件改不了。它的直接后果是【推头】：前轴横力不足，
 *  车实际转弯半径比前轮指向的更大。
 *
 *  后轮差速可以补偿这件事 —— 让后轴多转一点，把车"掰"过去：
 *
 *      新比例 = 1 + (原比例 − 1) × ACKERMANN_GAIN
 *
 *      1.0 = 标准（按 STEER_MAX_DEG 算出来的差速）
 *      >1  = 更激进，逐级补偿推头
 *      <1  = 更保守，补偿过度转向
 *
 *  ★ 直行时比例恒为 1，乘任何 GAIN 都不变，所以不会有副作用。
 *  ★ 调法：先跑 1.0；如果转不过来、往外跑（推头）就每次 +0.1；
 *         如果甩尾、转多了就往下调。建议范围 0.8 ~ 1.3。
 * ==========================================================================*/
#define ACKERMANN_GAIN  1.1f

/* ============================================================================
 *  第 5.5 部分：★★ 底盘功率限制（裁判系统规则）★★
 * ============================================================================
 *  规则要点（裁判系统说明书第 7 章）：
 *    - 电源管理模块在 CAN 上用 stdID = 0x31、1M、4 字节反馈：
 *        第 1~2 字节：底盘功率，单位 0.1W（int16，高字节在前）
 *        第 3~4 字节：缓冲能量，单位 0.1J（int16，高字节在前）
 *    - 底盘功率超限时，每 1ms 按"超出的瓦数 × 0.001J"扣缓冲能量；
 *      缓冲能量低于 0J 会被断电 5 秒。
 *
 *  控制思路（滑块里的算法）：
 *      速度环算出各路电流 I
 *        -> 用功率模型预测 F(k) = A·k² + B·k + L
 *        -> 解出满足 F(k) ≤ P 的最大 k
 *        -> 实际发出去 I' = k·I
 *
 *        A = R · ΣI²            （铜损项）
 *        B = K · Σ(I · n)       （机械功率项，n 是转子 rpm）
 *        L                      （与电流无关的基线功耗）
 *        k = (−B + √(B² + 4AC)) / (2A) ，C = P − L
 *
 *  ★ 下面 R / K / L 用的是滑块里的教学假设值。
 *    真车要标定：让模型算出的 g_power.p_pred_w 和 0x31 实测的
 *    g_power.power_w 尽量接近（匀速跑几个工况对比着调）。
 * ==========================================================================*/

/* 开关：1 = 启用功率限制；0 = 直接放行（调试用） */
#define POWER_LIMIT_ENABLE   1

/* 允许功率 P（W）
 * ★ 按当年规则和这台机器人的等级填。现在是 35W。
 *   改这个数不用动别的地方 —— 公式里的 C = P − L 会自动跟着变。 */
#define POWER_LIMIT_W        35.0f

/* 基线功耗 L（W）：不随电机电流变化的部分（主控、传感器等） */
#define POWER_BASE_W         5.0f

/* 等效电阻 R（Ω）：铜损系数 */
#define POWER_R_OHM          0.10f

/* 机械功率系数 K（W/(A·rpm)） */
#define POWER_K_COEF         0.0012f

/* 电流单位换算：电调 -16384~+16384 对应 -20A~+20A */
#define POWER_RAW_PER_AMP    819.2f

/* 缓冲能量保护（可选）
 *   1 = 缓冲能量低时再额外降额，给裁判系统的扣能留余量
 *   0 = 只用上面的功率模型
 * ★ 只有在收到过 0x31（功率模块在线）时才生效，
 *   没接模块不会因为"缓冲能量=0"把功率压死。 */
#define POWER_BUFFER_PROTECT 1

/* 缓冲能量低于这个值开始额外降额（J） */
#define POWER_BUFFER_LOW_J   30.0f

/* 缓冲能量低到这个值时功率压到 0（J） */
#define POWER_BUFFER_MIN_J   5.0f

/* 功率模块反馈超时（ms）：超过这么久没收到 0x31 就当作离线。
 *
 * ★ 为什么需要它？
 *   g_power.online 一旦置 1 就不会自己清零，模块掉线后
 *   buffer_j 会【冻结】在最后一次收到的值上。
 *   如果那个值恰好很低，缓冲保护会把功率永久压住 ——
 *   车越跑越没劲，而调试器里 online 还是 1，根本看不出原因。
 *   加上超时判断后，掉线就自动退回"只用功率模型"，不会再被旧数据坑。 */
#define POWER_FB_TIMEOUT_MS  100U

