/**
  ******************************************************************************
  * @file    drv_dbus.h
  * @brief   大疆 DBUS 遥控器协议（就是你原来那份，结构体原样保留）
  *
  * ============================================================================
  *  这个文件在干嘛？一句话：
  *     遥控器每 14ms 送来 18 个字节，这个文件定义"这 18 个字节怎么摆"，
  *     并提供 3 个函数让别的文件取值。
  *
  * ============================================================================
  *  18 个字节的排布（大疆定的，不能改）
  * ============================================================================
  *   字节      内容                              用几位
  *   --------------------------------------------------------------
  *   byte0     ch0 的低 8 位                       8 位
  *   byte1     ch0 的高 3 位 + ch1 的低 5 位       3+5 位
  *   byte2     ch1 的高 6 位 + ch2 的低 2 位       6+2 位
  *   byte3     ch2 的中间 8 位                     8 位
  *   byte4     ch2 的最高 1 位 + ch3 的低 7 位     1+7 位
  *   byte5     ch3 的高 4 位 + s1 + s2             4+2+2 位
  *   byte6~7   鼠标 X
  *   byte8~9   鼠标 Y
  *   byte10~11 鼠标滚轮
  *   byte12    鼠标左键
  *   byte13    鼠标右键
  *   byte14~15 键盘
  *   byte16~17 保留
  *
  * ============================================================================
  *  下面这个 union 为什么是对的（你之前写的，是对的）
  * ============================================================================
  *  ARM 上的 GCC 有几个规矩：
  *    1. 小端模式：低位字节放在低地址
  *    2. 位域从存储单元的【最低位】开始分配
  *    3. 一个字节装不下，自动换下一个字节
  *
  *  所以按下面的顺序声明：
  *      uint8_t ch0_h : 8;   -> 占 byte0 的 bit0~7
  *      uint8_t ch0_l : 3;   -> 占 byte1 的 bit0~2
  *      uint8_t ch1_h : 5;   -> 占 byte1 的 bit3~7
  *      ...
  *  一字节一字节地，正好和上面那张表对上。
  *
  *  所以 union 里的 data 和 buf[18] 是【同一块内存】：
  *      往 buf 里 memcpy 数据
  *      等于往 data 里 memcpy
  *  完全没问题。
  *
  *  ★ 唯一要小心的地方：
  *     变量名 ch0_h 里的 h 不代表"高字节"，
  *     它实际装的是 ch0 的【低 8 位】。名字起得有点误导。
  *     所以读摇杆值请统一用下面的 DBUS_GetChannel()，
  *     不要自己去读 ch0_h 然后瞎拼。
  *
  * ============================================================================
  *  通道值的范围
  * ============================================================================
  *     364  = 摇杆推到最小
  *     1024 = 摇杆在中位（松手）
  *     1684 = 摇杆推到最大
  *  拨杆 s1 / s2：1 = 拨到上，2 = 拨到中，3 = 拨到下。
  ******************************************************************************
  */
#ifndef __DRV_DBUS_H
#define __DRV_DBUS_H

#include "main.h"

/* 一帧固定 18 字节。全工程凡是要写 18 的地方都用这个宏。 */
#define DBUS_LEN  18

#pragma pack(1)
/* 上面这行：关掉编译器的"自动对齐"。
   如果开着自动对齐，结构体会被补成 20 字节，和协议的 18 字节对不上，
   后面所有字段全部错位。
   #pragma pack() 在文件末尾把它恢复回去。 */

/**
  * @brief 遥控器一帧数据的容器
  * @note  union（联合体）的意思：里面的成员【共用同一块内存】。
  *        - 往 buf[18] 里 memcpy
  *        - 就能从 data.rc.xxx 里读到字段
  *        两者是同一块数据，不需要转换。
  */
typedef union {

    struct {

        /* 对应协议的 byte0 ~ byte5：摇杆 + 拨杆 */
        struct {
            uint8_t ch0_h : 8;   /* byte0 的 bit0~7  -> ch0 的低 8 位 */
            uint8_t ch0_l : 3;   /* byte1 的 bit0~2  -> ch0 的高 3 位 */
            uint8_t ch1_h : 5;   /* byte1 的 bit3~7  -> ch1 的低 5 位 */
            uint8_t ch1_l : 6;   /* byte2 的 bit0~5  -> ch1 的高 6 位 */
            uint8_t ch2_h : 2;   /* byte2 的 bit6~7  -> ch2 的低 2 位 */
            uint8_t ch2_m : 8;   /* byte3 的 bit0~7  -> ch2 的中间 8 位 */
            uint8_t ch2_l : 1;   /* byte4 的 bit0    -> ch2 的最高 1 位 */
            uint8_t ch3_h : 7;   /* byte4 的 bit1~7  -> ch3 的低 7 位 */
            uint8_t ch3_l : 4;   /* byte5 的 bit0~3  -> ch3 的高 4 位 */
            uint8_t s1 : 2;      /* byte5 的 bit4~5  -> 拨杆 S1 */
            uint8_t s2 : 2;      /* byte5 的 bit6~7  -> 拨杆 S2 */
        } rc;

        /* 对应协议的 byte6 ~ byte13：鼠标 */
        struct {
            int16_t x;           /* byte6~7   鼠标 X */
            int16_t y;           /* byte8~9   鼠标 Y */
            int16_t z;           /* byte10~11 鼠标滚轮 */
            uint8_t press_l;     /* byte12    左键，1=按下 */
            uint8_t press_r;     /* byte13    右键，1=按下 */
        } mouse;

        /* 对应协议的 byte14 ~ byte15：键盘 */
        struct {
            uint16_t v;          /* byte14~15 键盘按键编码 */
        } key;

        uint16_t resv;           /* byte16~17 保留，用不到 */

    } data;

    uint8_t buf[DBUS_LEN];       /* 18 个字节，和上面的 data 共用内存。
                                    memcpy 的目标就是它。 */

} RC_Ctl_Define_t;

#pragma pack()
/* 上面这行：恢复编译器的自动对齐，免得影响后面定义的结构体。 */

/* ============================================================================
 *  下面 3 个函数，每个都写清楚了"在哪被调用"
 * ==========================================================================*/

/**
  * @brief  取出第 ch 个摇杆通道的值
  * @note   调用位置：App/Task/task_chassis.c 的 Task_Chassis_Loop() 里，
  *                   每 1 毫秒调用一次（要用几个通道就调几次）。
  * @note   实现位置：App/Driver/drv_dbus.c
  * @param  rc  遥控器数据（一般传 &rc_data）
  * @param  ch  通道号，只能是 0 / 1 / 2 / 3
  * @retval 0 ~ 2047。正常范围 364(最小) / 1024(中位) / 1684(最大)
  */
uint16_t DBUS_GetChannel(const RC_Ctl_Define_t *rc, uint8_t ch);

/**
  * @brief  取拨杆 S1 / S2
  * @note   调用位置：目前没用到。以后要"拨杆切模式"时在这里取。
  * @note   实现位置：App/Driver/drv_dbus.c
  * @param  rc     遥控器数据
  * @param  which  传 1 取 S1，传其它值取 S2
  * @retval 1 = 上，2 = 中，3 = 下
  */
uint8_t DBUS_GetSwitch(const RC_Ctl_Define_t *rc, uint8_t which);

/**
  * @brief  把遥控器数据强制改成"摇杆全部回中"的安全值
  * @note   调用位置：App/Task/task_rc.c 的 Task_RC_Loop() 里，
  *                   判断出"关控"（超过 21ms 没收到数据）时调用。
  * @note   实现位置：App/Driver/drv_dbus.c
  * @param  rc  要修改的遥控器数据（一般传 &rc_data）
  * @retval 无
  *
  * @note   ★ 这个函数是干什么用的？
  *           关控的时候，rc_data 里还留着"关控前最后一帧"的摇杆位置。
  *           万一有其他代码去读它，读到的就是关控那一刻你手里的杆位，
  *           非常危险。
  *           调用这个函数之后，rc_data 就变成"摇杆在中位、拨杆在中位"，
  *           任何地方读它都是安全值。
  */
void DBUS_SetSafeValue(RC_Ctl_Define_t *rc);

#endif
