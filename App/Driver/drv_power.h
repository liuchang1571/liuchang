/**
  ******************************************************************************
  * @file    drv_power.h
  * @brief   底盘功率限制（裁判系统规则）
  *
  * ============================================================================
  *  一、为什么要限功率？
  * ============================================================================
  *  裁判系统会实时监视底盘功率。超限时它会扣"缓冲能量"：
  *     每 1ms，每超出 1W 就扣 0.001J（缓冲能量上限 60J，下限 -10J）
  *  缓冲能量掉到 0 以下，底盘会被【直接断电 5 秒】—— 那基本等于这局废了。
  *
  *  所以速度环算出来的电流不能直接发出去，要先乘一个统一系数 k：
  *
  *      I' = k · I      （k 越大越猛，0 ≤ k ≤ 1）
  *
  * ============================================================================
  *  二、k 怎么求？（滑块里的算法）
  * ============================================================================
  *  功率模型（把每个轮子的功率加起来）：
  *
  *      F(k) = A·k² + B·k + L
  *      A = R · ΣI²          ← 铜损项（和电流平方成正比）
  *      B = K · Σ(I·n)       ← 机械功率项（n 是转子 rpm）
  *      L                    ← 和电流无关的基线功耗
  *
  *  要"在不超 P 的前提下让 k 尽量大"，就是解
  *
  *      A·k² + B·k + (L − P) = 0
  *      k = (−B + √(B² + 4AC)) / (2A)      ，C = P − L
  *
  *  两种情况不用解：
  *      F(1) ≤ P  →  k = 1（本来就不超，不缩）
  *      C ≤ 0     →  k = 0（允许功率还不够基线功耗）
  *
  *  算完把 k 限制在 0~1，再乘回每一路电流。
  *
  * ============================================================================
  *  三、功率数据从哪来？
  * ============================================================================
  *  电源管理模块在 CAN 上用 stdID = 0x31、1M、4 字节反馈：
  *      第 1~2 字节：底盘功率，单位 0.1W（int16，高字节在前）
  *      第 3~4 字节：缓冲能量，单位 0.1J（int16，高字节在前）
  *
  *  ★ 它不在 0x200~0x20F 那一段里，所以 bsp_can.c 的过滤器专门
  *    多开了一组只匹配 0x31 的，否则硬件会把这帧直接丢掉。
  *
  * ============================================================================
  *  四、模块对外只提供 3 个函数
  * ============================================================================
  *      Power_Init()            开机一次
  *      Power_UpdateFeedback()  在 CAN 中断里收到 0x31 时调用
  *      Power_CalcScale()       底盘任务每 1ms 调用，返回 k
  *
  *  调试时直接看全局变量 g_power（下面有 typedef 说明每个字段）。
  ******************************************************************************
  */
#ifndef __DRV_POWER_H
#define __DRV_POWER_H

#include "main.h"

/**
  * @brief 功率限制的全部状态
  * @note  全局就一个对象 g_power，调试器里展开它就能看到所有中间量。
  */
typedef struct {

    /* ---------- 来自 0x31 的反馈 ---------- */
    float power_w;          /* 实测底盘功率，单位 W */
    float buffer_j;         /* 缓冲能量，单位 J（上限 60，下限 -10） */
    uint32_t last_rx_tick;  /* 最后一次收到 0x31 的时刻 */
    uint8_t online;         /* 1 = 收到过功率模块的帧 */

    /* ---------- 本拍算出来的结果 ---------- */
    float scale;            /* 统一缩放系数 k：0 ~ 1 */
    uint8_t limiting;       /* 1 = 正在限功率（k < 1） */
    float buffer_scale;     /* 缓冲能量保护单独算出的系数 */

    /* ---------- 中间量（标定 R/K 时看这几个） ---------- */
    float p_pred_w;         /* F(1)：完全不缩放时的预测功率 W */
    float a_coef;           /* 公式里的 A */
    float b_coef;           /* 公式里的 B */

} Power_t;

/* 全局唯一的功率限制对象（★ 调试入口就在这里） */
extern Power_t g_power;

/**
  * @brief  初始化功率限制模块
  * @note   调用位置：App/Task/task_chassis.c 的 Task_Chassis_Init()。【开机一次】
  * @param   无
  * @retval  无
  */
void Power_Init(void);

/**
  * @brief  收到功率模块的反馈（★ 只能在 CAN 中断里调用）
  * @note   调用位置：App/Bsp/bsp_can.c 的
  *                   HAL_CAN_RxFifo0MsgPendingCallback()，收到 0x31 时
  * @param  power_0p1w   底盘功率，单位 0.1W（原样传，函数内部换算）
  * @param  buffer_0p1j  缓冲能量，单位 0.1J
  * @retval  无
  */
void Power_UpdateFeedback(int16_t power_0p1w, int16_t buffer_0p1j);

/**
  * @brief  算这一拍该乘的缩放系数 k
  * @note   调用位置：App/Task/task_chassis.c 的 Task_Chassis_Loop()，
  *                   在速度环 PID 之后、发 CAN 之前，每 1ms 一次
  * @param  i_raw  各路电流（-16384 ~ +16384），传 give_current
  * @param  rpm    对应的实测转速（转子 rpm），传 actual_rpm
  * @param  cnt    路数（本车 2 路；公式对任意路数都成立）
  * @retval 0.0 ~ 1.0 的系数
  */
float Power_CalcScale(const int16_t i_raw[], const int16_t rpm[], uint8_t cnt);

#endif
