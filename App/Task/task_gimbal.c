/**
  ******************************************************************************
  * @file    task_gimbal.c
  * @brief   云台 + 发射：1kHz 任务
  *
  * ============================================================================
  *  为什么单独开一个任务（而不是塞在底盘循环里）
  * ============================================================================
  *   1. 底盘以后要加陀螺仪（INS 任务 + 姿态解算），把云台隔离出来，
  *      底盘那边加多重的东西都拖不慢云台。
  *   2. CAN1 上 4 个电机（pitch / 拨弹 / 摩擦L / 摩擦R）共用 `0x200` 一帧，
  *      本任务"算完就发"，天然同一拍；
  *      如果拆成"一个任务算、另一个任务发"，会出现这帧里 pitch 是这拍的、
  *      摩擦轮是上一拍的（错拍），PID 会莫名其妙地抖。
  *   3. 所以分工是：**CAN1 归云台任务，CAN2 归底盘任务**，
  *      每个任务独占自己的总线，不跨任务传电流。
  *
  * ============================================================================
  *  和底盘任务的共享数据（都是只读，不需要加锁）
  * ============================================================================
  *      rc_data / rc_lost_flag  —— 底盘任务里 Task_RC_Loop() 更新；
  *                                  这里最多晚 1ms 读到，对 14ms 一帧的遥控没影响
  *      g_vehicle_fault         —— 以后陀螺仪置位（pitch/roll > 80°），两个任务都看
  *
  * ============================================================================
  *  CAN1 每 1ms 发两帧
  * ============================================================================
  *      0x200  槽0 pitch(1)  槽1 拨弹(2)  槽2 摩擦L(3)  槽3 摩擦R(4)
  *      0x1FF  槽0 yaw(1)
  ******************************************************************************
  */
#include "task_gimbal.h"
#include "config_gimbal.h"
#include "config_shooter.h"
#include "config.h"          /* rc_data / rc_lost_flag */
#include "driver_gimbal.h"   /* g_gimbal / g_vehicle_fault */
#include "driver_shooter.h"  /* g_shooter */
#include "drv_dbus.h"        /* DBUS_GetChannel / DBUS_GetSwitch */
#include "bsp_can.h"         /* CAN_Send4 */

#include "FreeRTOS.h"
#include "task.h"

#include <math.h>

/* ============================================================================
 *  Task_Gimbal_Init —— 初始化云台 + 发射
 *  调用者：freertos.c 的 Init_Task（StartTask04），在 g_sys_ready 之前
 * ==========================================================================*/
void Task_Gimbal_Init(void)
{
    Gimbal_Init();      /* yaw 6020 + pitch 3508：对象和四个环的 PID 参数 */
    Shooter_Init();     /* 2 个摩擦轮 + 拨弹盘 */
}

/* ============================================================================
 *  Task_Gimbal_Loop —— 1kHz 主循环（不返回）
 * ==========================================================================*/
void Task_Gimbal_Loop(void)
{
    TickType_t last_wake;
    int16_t    cur4[4];
    int16_t    volt4[4];

    last_wake = xTaskGetTickCount();

    for (;;)
    {
        /* ============================================================
         *  ① 关节角：不管什么状态都要更新
         *     （6020 单圈绝对编码器，手转云台也要能看到）
         * ========================================================== */
        Gimbal_UpdateJointAngle();

        /* ============================================================
         *  ② 控制
         * ------------------------------------------------------------
         *  关控 / 全车失能 -> 全部 0 输出，目标跟住实测，恢复时不弹回
         * ========================================================== */
        if ((rc_lost_flag == 0) && (g_vehicle_fault == 0))
        {
            /* 云台：增量式摇杆（推着转、松手停） */
            Gimbal_StickUpdate((int16_t)DBUS_GetChannel(&rc_data, 0),   /* ch0 */
                               (int16_t)DBUS_GetChannel(&rc_data, 1));  /* ch1 */
            Gimbal_Control();

            /* 发射：S1 选模式（1 单发 / 2 连发），S2 拨到 1 发射 */
            Shooter_Update(DBUS_GetSwitch(&rc_data, 1),     /* S1 */
                           DBUS_GetSwitch(&rc_data, 2));    /* S2 */
        }
        else
        {
            Gimbal_TrackCurrent();
            Gimbal_SafeOutput();
            Shooter_SafeOutput();
        }

        /* ============================================================
         *  ③ 发 CAN1
         * ------------------------------------------------------------
         *  ★ 电调没有超时保护：不管什么状态都必须每 1ms 发一次。
         * ========================================================== */

        /* 0x200：一帧 4 个 3508 */
        cur4[0] = g_gimbal.pitch_cur;
        cur4[1] = g_shooter.feeder_cur;
        cur4[2] = g_shooter.fric_l_cur;
        cur4[3] = g_shooter.fric_r_cur;
        CAN_Send4(&hcan1, 0x200, cur4);

#if (STEER_ON_CAN1 == 0)
        /* 0x1FF：yaw 6020 电压（槽0）
         *
         * ★ 只在【转向电机不在 CAN1 上】时才发这一帧。
         *   因为一帧 0x1FF 会覆盖全部 4 个槽：如果转向电机也接在 CAN1，
         *   这一帧里的 0 会把它的控制量反复清零，电机就变成"时有时无"。
         *   转向接在 CAN1 时，这帧由底盘任务发（BSP_CAN_Send_Steer_Voltage），
         *   全总线只有一个 0x1FF 发送者。 */
        volt4[0] = g_gimbal.yaw_volt;
        volt4[1] = 0;
        volt4[2] = 0;
        volt4[3] = 0;
        CAN_Send4(&hcan1, 0x1FF, volt4);
#else
        (void)volt4;    /* 这帧不发了，只占位，避免"未使用变量"警告 */
#endif

        /* ============================================================
         *  ④ 严格等 1ms
         * ========================================================== */
        vTaskDelayUntil(&last_wake, pdMS_TO_TICKS(1));
    }
}
