/**
  ******************************************************************************
  * @file    bsp_can.h
  * @brief   CAN2 收发（BSP 层）—— 后轮 3508 驱动 + 前轮 6020 转向
  *
  * ============================================================================
  *  CAN2 上总共只有 4 种帧
  * ============================================================================
  *   方向     帧 ID        内容                                谁发的
  *   ---------------------------------------------------------------------
  *   本板发   0x200    后轮 2 个 3508 的电流（每个 2 字节）    本板
  *   本板发   0x1FF    前轮 2 个 6020 的电压（每个 2 字节）    本板
  *   本板收   0x201~   3508 的反馈（角度/rpm/电流/温度）       电调自己发
  *   本板收   0x205~   6020 的反馈（角度/rpm/电流/温度）       电机自己发
  *
  * ============================================================================
  *  反馈帧的 8 个字节怎么读（两种电机的格式完全一样）
  * ============================================================================
  *      字节 0~1  : 转子机械角度，0 ~ 8191（一圈分 8192 份）
  *      字节 2~3  : 转子转速 rpm，有符号（正转/反转）
  *      字节 4~5  : 实际转矩电流，有符号
  *      字节 6    : 温度（摄氏度）
  *      字节 7    : 保留
  *  所有 2 字节的数据都是【高字节在前】。
  ******************************************************************************
  */
#ifndef __BSP_CAN_H
#define __BSP_CAN_H

#include "main.h"

/**
  * @brief  CAN2 初始化（"点火"）
  * @note   调用位置：Core/Src/freertos.c 的 Init_Task（StartTask04）里，
  *                   开机一次，而且在 Task_RC_Init() 之前
  * @note   实现位置：App/Bsp/bsp_can.c
  * @param   无
  * @retval  无
  *
  * @note   ★★ 这一步是"CAN 完全没反应"最常见的原因 ★★
  *         CubeMX 生成的 MX_CAN2_Init() 只把参数配好，
  *         CAN 依然停在"初始化模式"，此时它既不发送也不接收。
  *         更坑的是：这种情况下 HAL_CAN_AddTxMessage() 还会返回"成功"，
  *         你以为发出去了，其实总线上什么都没有。
  *         必须调用 HAL_CAN_Start() 才会退出初始化模式。
  *         另外不配置过滤器的话，一帧反馈也收不到。
  */
void BSP_CAN_Init(void);

/**
  * @brief  给后轮两个 3508 发电流指令
  * @note   调用位置：App/Task/task_chassis.c 的 Task_Chassis_Loop()，
  *                   每 1 毫秒调用一次（速度环的输出）
  * @note   实现位置：App/Bsp/bsp_can.c
  * @param  left   左后轮电流，-16384 ~ +16384
  * @param  right  右后轮电流，-16384 ~ +16384
  * @retval  无
  *
  * @note   ★ 电调没有"超时保护"：
  *           你不发，它就保持上一次的电流一直转。
  *           所以必须每 1ms 发一次，哪怕电流是 0 也要发。
  */
void BSP_CAN_Send_Drive_Current(int16_t left, int16_t right);

/**
  * @brief  给前轮转向的 6020 发电压指令
  * @note   调用位置：App/Task/task_chassis.c 的 Task_Chassis_Loop()，
  *                   每 1 毫秒调用一次（位置环的输出）
  * @note   实现位置：App/Bsp/bsp_can.c
  * @param  voltage  转向电压，-30000 ~ +30000
  * @retval  无
  *
  * @note   ★ 只有【一个】转向电机（它推齿条），所以这里只有一个参数。
  */
void BSP_CAN_Send_Steer_Voltage(int16_t voltage);

#endif
